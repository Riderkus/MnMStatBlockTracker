import { chromium } from 'playwright';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';
// Screenshots go next to the tests; the app is the folder above.
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), 'shots'); fs.mkdirSync(OUT, { recursive: true });
const BASE = 'http://127.0.0.1:8765';
const browser = await chromium.launch();
const errors = [];
const log = (label, s) => console.log(label.padEnd(44), s);
const p = await browser.newPage({ viewport: { width: 1280, height: 900 } });
p.on('pageerror', (e) => errors.push(e.message));
p.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await p.goto(`${BASE}/index.html`);
await p.evaluate(() => document.fonts.ready);
await p.click('#btn-new'); await p.click('#type-dialog [data-type="minion"]'); await p.fill('#f-name', 'Thugs');
const stored = async () => { await p.waitForTimeout(450); return p.evaluate(() => JSON.parse(localStorage.getItem('statblocks.v1')).blocks[0].minions); };
const counters = () => p.evaluate(() => (document.getElementById('play-counters').textContent).replace(/\s+/g, ' ').trim());
const meta = () => p.evaluate(() => document.querySelector('.block-item .meta').textContent.replace(/\s+/g, ' ').trim() + ' | ' + document.querySelector('.block-item .badges').textContent);
const ensure = async (v) => { const label = await p.textContent('#btn-play'); if ((v === 'play') === (label === 'Play')) await p.click('#btn-play'); };

log('editor: Number field shown for a minion:', await p.evaluate(() => getComputedStyle(document.querySelector('#f-minions').closest('label')).display !== 'none'));
await p.fill('#f-minions', '4');
log('typed 4, stored:', JSON.stringify(await stored()));
log('list meta:', await meta());
await ensure('play');
log('play counters:', await counters());
await p.click('.counter:has-text("Down") .btn:nth-of-type(2)');
log('Down +: counters / stored / list:', (await counters()) + ' / ' + JSON.stringify(await stored()) + ' / ' + (await meta()));
for (let i = 0; i < 4; i++) await p.click('.counter:has-text("Down") .btn:nth-of-type(2)');
log('Down + four more (capped at 4, Up 0):', (await counters()) + ' / ' + (await meta()));
await p.screenshot({ path: `${OUT}/minions-play.png`, clip: { x: 370, y: 330, width: 860, height: 140 } });
await p.click('.counter:has-text("Minions") .btn:nth-of-type(1)');
log('Minions - to 3: down follows:', (await counters()) + ' / ' + JSON.stringify(await stored()));
await p.click('#play-conds .btn:has-text("Clear")');
log('Clear: all back up:', (await counters()) + ' / ' + (await meta()));
await p.click('#btn-undo');
log('Undo: down again:', await counters());
await p.click('.counter:has-text("Down") .btn:nth-of-type(1)');
log('Down -:', await counters());
await p.reload(); await p.click('.block-item');
log('after reload:', (await counters()) + ' / ' + JSON.stringify(await stored()));
await ensure('edit');
log('editor Number field after reload:', await p.inputValue('#f-minions'));
await p.hover('#f-minions'); await p.waitForTimeout(600);
log('info card on Number:', await p.evaluate(() => { const c = document.getElementById('info-pop'); return c.hidden ? 'hidden' : c.textContent.trim().slice(0, 40); }));
await p.mouse.move(5, 5);
// a non-minion is untouched by all this
await p.click('#btn-new'); await p.click('#type-dialog [data-type="block"]'); await p.fill('#f-name', 'Hero');
log('stat block: Number field hidden:', await p.evaluate(() => getComputedStyle(document.querySelector('#f-minions').closest('label')).display === 'none'));
await ensure('play');
log('stat block play counters:', await counters());
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
